import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import { article, breadcrumbs, graph, pageMeta, serialiseJsonLd } from '@morph/seo';
import { publishedContent, siteIdentity } from '../../../lib/site.js';

/**
 * An article.
 *
 * The page where the SEO and compliance designs meet: the structured data states that
 * a piece was machine-generated, names the human who reviewed it, and carries its
 * sources in `isBasedOn` — which is simultaneously the schema.org citation mechanism
 * and the mandatory attribution the content pipeline requires. The same list is
 * rendered visibly, because a source a reader cannot see is not an attribution.
 */

interface Params {
  readonly slug: string;
}

function findContent(slug: string) {
  return publishedContent().find((item) => item.slug === slug);
}

/**
 * Pre-render the known slugs.
 *
 * Content pages are not adaptive — the hero and the theme are, but the words are not —
 * so they can be static and revalidated. That is what keeps an article fast without
 * giving up the adaptive shell around it.
 */
export function generateStaticParams(): Params[] {
  return publishedContent().map((item) => ({ slug: item.slug }));
}

export async function generateMetadata({ params }: { params: Promise<Params> }): Promise<Metadata> {
  const { slug } = await params;
  const content = findContent(slug);
  if (content === undefined) return { title: 'Not found' };

  const site = siteIdentity();
  const meta = pageMeta({
    origin: site.origin,
    siteName: site.name,
    path: `/t/${content.slug}`,
    title: content.title,
    description: content.summary,
    type: 'article',
    publishedAt: content.publishedAt,
    ...(content.modifiedAt === undefined ? {} : { modifiedAt: content.modifiedAt }),
  });

  return {
    title: content.title,
    description: content.summary,
    alternates: { canonical: meta.canonical },
    openGraph: {
      type: 'article',
      title: content.title,
      description: content.summary,
      url: meta.canonical,
      publishedTime: content.publishedAt,
    },
  };
}

export default async function ArticlePage({
  params,
}: {
  params: Promise<Params>;
}): Promise<React.JSX.Element> {
  const { slug } = await params;
  const content = findContent(slug);
  if (content === undefined) notFound();

  const site = siteIdentity();

  const structuredData = serialiseJsonLd(
    graph([
      article(site, {
        headline: content.title,
        description: content.summary,
        slug: content.slug,
        publishedAt: content.publishedAt,
        ...(content.modifiedAt === undefined ? {} : { modifiedAt: content.modifiedAt }),
        sources: content.sources,
        ...(content.generatedBy === undefined ? {} : { generatedBy: content.generatedBy }),
        ...(content.reviewedBy === undefined ? {} : { reviewedBy: content.reviewedBy }),
        keywords: content.keywords,
      }),
      breadcrumbs([
        { name: 'Home', url: `${site.origin}/` },
        { name: content.title, url: `${site.origin}/t/${content.slug}` },
      ]),
    ]),
  );

  return (
    <>
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: structuredData }} />
      <main id="main" className="shell">
        <article>
          <header>
            <h1>{content.title}</h1>
            <p className="muted">
              <time dateTime={content.publishedAt}>{content.publishedAt.slice(0, 10)}</time>
              {content.generatedBy !== undefined && (
                <>
                  {' · '}
                  {/*
                    Stated plainly, in the markup a reader sees, not only in structured
                    data a machine reads. Labelling generation only where it is
                    convenient is not labelling it.
                  */}
                  <span>
                    Generated by {content.generatedBy}
                    {content.reviewedBy !== undefined && `, reviewed by ${content.reviewedBy}`}
                  </span>
                </>
              )}
            </p>
          </header>

          <p style={{ fontSize: '1.1875rem' }}>{content.summary}</p>

          <section aria-labelledby="sources">
            <h2 id="sources">Sources</h2>
            <ul className="muted" style={{ maxWidth: 'var(--measure)' }}>
              {content.sources.map((source) => (
                <li key={source.url}>
                  <a href={source.url} rel="noopener nofollow">
                    {source.title}
                  </a>
                  {' — '}
                  {source.publisher}
                </li>
              ))}
            </ul>
          </section>
        </article>
      </main>
    </>
  );
}
