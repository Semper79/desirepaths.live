/**
 * The largest body this will read.
 *
 * A beacon is at most 50 events and each event is bounded by its schema, so 256 KB is
 * generous. It exists because `await request.text()` on an unbounded body is how a Worker
 * meets its 128 MB memory limit, and `Content-Length` is a claim the client makes rather
 * than a fact — so the cap is enforced on the bytes actually read, not on the header.
 */
const MAX_BODY_BYTES = 256 * 1024;

/**
 * How many beacons one anonymous id may send per minute.
 *
 * D34 explains why this is a looser guarantee than the token bucket it replaces, and why
 * the per-beacon event cap in `IngestBatchSchema` is what keeps the worst case bounded.
 */
const RATE_LIMIT_PERIOD_SECONDS = 60;

/**
 * The bindings `wrangler.jsonc` declares.
 *
 * Hand-written rather than generated by `wrangler types`, and that is a deliberate
 * exception to Cloudflare's own advice: the generated `Env` is a global ambient
 * declaration, and this repository compiles four apps and eight packages in one
 * `tsc --noEmit` pass where an ambient `Env` would leak into all of them. The cost is that
 * this interface can drift from the config, so `/ready` checks the bindings at runtime
 * rather than trusting the type.
 */
interface Env {
  /** The behavioural event stream. Sampled, and never a posterior's input (D33). */
  readonly EVENTS: EventDataset;
  /** `morph_*` instrument observations. A separate dataset so the two sample apart. */
  readonly METRICS: AnalyticsEngineLike;
  readonly INGEST_LIMITER: { limit(options: { key: string }): Promise<{ success: boolean }> };
  /**
   * Optional because a secret that has not been set is absent at runtime, whatever the
   * binding's type says — and this one is read by the probe that exists to report its
   * absence. See `usablePepper`.
   */
  readonly ANON_ID_PEPPER?: string;
  readonly MORPH_PUBLIC_URL: string;
  readonly MORPH_TIMEZONE: string;
  /**
   * The data controller (D4). Not optional in practice: without all three the collector
   * refuses every beacon, because measuring a visitor who has not been told who is
   * responsible is the one thing Art. 13 does not permit.
   */
  readonly MORPH_CONTROLLER_NAME?: string;
  readonly MORPH_CONTROLLER_ADDRESS?: string;
  readonly MORPH_CONTROLLER_EMAIL?: string;
  readonly MORPH_CONTROLLER_DPO_EMAIL?: string;
  /**
   * The exact per-variant counters (D33), one object per surface.
   *
   * Declared in this Worker rather than in the cron that reads them, because a Durable
   * Object class lives in exactly one script and this is the one that writes to it on
   * every beacon. The cron binds to the same namespace with `script_name`.
   */
  /**
   * One object per session, which folds it and closes itself (D36).
   *
   * The collector hands a beacon's events here and does not wait for a verdict: whether a
   * session converted is not knowable until it ends, and the beacon has already been
   * discarded by the browser.
   */
  readonly SESSIONS: SessionWriter;
}

/**
 * The only thing the collector may do to a session: address one and hand it events.
 *
 * Narrower than `DurableObjectNamespace<SessionAggregate>` on purpose. The full namespace
 * type would also expose `alarm()` and `state()`, and the collector has no business
 * closing a session or reading one back — closing is the alarm's decision and reading is
 * the operator's. A real namespace satisfies this structurally, so nothing is lost by
 * asking for less.
 *
 * The collector also has no `COUNTERS` binding at all, which is the same idea taken
 * further: the posteriors' source is reachable only from the session object, and the way to
 * guarantee that is to leave the capability out of this type rather than to remember not to
 * use it.
 */
interface SessionWriter {
  idFromName(name: string): DurableObjectId;
  get(id: DurableObjectId): { record(events: readonly FoldableEvent[]): Promise<void> };
}

/** A beacon's response is discarded; only the status and `retry-after` are ever read. */
function empty(status: number, headers?: Record<string, string>): Response {
  return new Response(null, { status, ...(headers === undefined ? {} : { headers }) });
}

/**
 * Read the body without trusting `Content-Length`.
 *
 * Returns `null` when the body exceeds the cap, which the caller turns into a 413. Reading
 * through the stream rather than calling `.text()` is the difference between refusing an
 * oversized payload and allocating it first.
 */
async function readBoundedText(request: Request): Promise<string | null> {
  const body = request.body;
  if (body === null) return '';

  // One assertion, and it is a type-resolution problem rather than a modelling one. This
  // project loads both `@types/node` and `@cloudflare/workers-types`; their
  // `ReadableStream` declarations differ, whichever wins hands back `any`, and the `any`
  // then spreads through every use below. Asserting once at the boundary keeps the rest of
  // the function honestly typed — the alternative is a second tsconfig for one file.
  const reader = body.getReader() as ReadableStreamDefaultReader<Uint8Array>;
  const chunks: Uint8Array[] = [];
  let total = 0;

  for (;;) {
    const { done, value } = await reader.read();
    // `value` is only absent when `done`, and that returns above.
    if (done) break;

    total += value.byteLength;
    if (total > MAX_BODY_BYTES) {
      await reader.cancel();
      return null;
    }
    chunks.push(value);
  }

  const joined = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    joined.set(chunk, offset);
    offset += chunk.byteLength;
  }

  return new TextDecoder().decode(joined);
}

/**
 * Whether this deployment is allowed to measure anybody (D4).
 *
 * Checked before the body is read, so an unconfigured deployment spends nothing on a
 * payload it will refuse. A 503 rather than a 403: the condition is temporary and fixable
 * by the operator, and a retrying client is the correct behaviour once it is fixed.
 *
 * This is the enforcement half of what `/privacy` publishes. The page says "nothing about
 * you is being recorded" in this state, and that sentence is only true because of this
 * function — the two read the same check from `@morph/core` so they cannot drift into
 * disagreeing.
 */
function mayMeasure(env: Env): boolean {
  return controllerFrom(env) !== null;
}

/**
 * The floor `/ready` reports on. A short pepper is not so much a weak one as a guessable
 * one, and an anonymous id that can be re-derived from a known IP is not anonymous.
 */
const PEPPER_MIN_LENGTH = 32;

/**
 * The pepper, or `null` when there is not a usable one.
 *
 * `/ready` used to read `env.ANON_ID_PEPPER.length` directly, trusting a type that says
 * the binding is always a string. On the one deployment that endpoint exists to describe —
 * the one where the secret has not been set yet — the property is `undefined` and the
 * probe answered with a Worker exception instead of the name of the missing variable. The
 * comment on `Env` already said the interface can drift from the config and that `/ready`
 * therefore checks at runtime; the check was the thing trusting the type.
 *
 * The ingest path needs it for a sharper reason. Without a pepper every visitor hashes to
 * the same anonymous id, so the collector would accept beacons and record data that looks
 * entirely plausible and is fiction. That is worse than refusing, so it refuses — and
 * separately from the controller gate, because "nobody has said who is responsible" and
 * "this deployment cannot tell two visitors apart" are different faults with different
 * fixes, and an operator reading `morph_ingest_errors` should not have to guess which.
 */
function usablePepper(env: Env): string | null {
  const pepper = env.ANON_ID_PEPPER;
  return pepper !== undefined && pepper.length >= PEPPER_MIN_LENGTH ? pepper : null;
}

async function handleIngest(
  request: Request,
  env: Env,
  ctx: ExecutionContext,
  publisher: EventPublisher,
): Promise<Response> {
  if (!mayMeasure(env)) {
    ingestRequests.inc({ outcome: 'rejected' });
    ingestErrors.inc({ reason: 'no_controller' });
    return empty(503, { 'retry-after': '3600' });
  }

  const pepper = usablePepper(env);
  if (pepper === null) {
    ingestRequests.inc({ outcome: 'rejected' });
    ingestErrors.inc({ reason: 'no_pepper' });
    return empty(503, { 'retry-after': '3600' });
  }

  const raw = await readBoundedText(request);
  if (raw === null) {
    ingestRequests.inc({ outcome: 'rejected' });
    ingestErrors.inc({ reason: 'body_too_large' });
    return empty(413);
  }

  let parsedBody: unknown;
  try {
    parsedBody = JSON.parse(raw);
  } catch {
    ingestRequests.inc({ outcome: 'rejected' });
    ingestErrors.inc({ reason: 'malformed_json' });
    return empty(400);
  }

  // `cf` is absent in `wrangler dev` without an internet route and in unit tests. `ZZ`
  // is the schema's own "unknown", so an absent country is recorded as unknown rather
  // than guessed at from the IP — which this process has already discarded by then.
  const country = (request.cf?.country ?? 'ZZ') as string;

  const meta: RequestMeta = {
    // The whole point of D34. Set by the Cloudflare edge, not by a proxy hop, and not
    // client-controllable. It is hashed inside `enrich` and never stored.
    ip: request.headers.get('cf-connecting-ip') ?? '0.0.0.0',
    userAgent: request.headers.get('user-agent') ?? undefined,
    acceptLanguage: request.headers.get('accept-language') ?? undefined,
    secFetchSite: request.headers.get('sec-fetch-site') ?? undefined,
    chUaMobile: request.headers.get('sec-ch-ua-mobile') ?? undefined,
    chUaPlatform: request.headers.get('sec-ch-ua-platform') ?? undefined,
    country: country.slice(0, 2).toUpperCase(),
    hasCookies: request.headers.get('cookie') !== null,
    consentMask: consentMaskFromCookie(request.headers.get('cookie') ?? undefined),
    now: new Date(),
  };

  const result = await enrich(parsedBody, meta, {
    // Constructed per request rather than memoised: it holds the pepper, which comes from
    // `env`, and `env` is request-scoped. The class does no I/O, so this costs nothing.
    identity: new VisitorIdentity(pepper),
    selfHost: new URL(env.MORPH_PUBLIC_URL).hostname,
    timezone: env.MORPH_TIMEZONE,
  });

  for (const rejection of result.rejected) {
    ingestErrors.inc({ reason: rejection.reason });
  }

  // A wholly malformed body is a client bug worth telling the client about; a partial
  // rejection is not, because the beacon has already been discarded by the browser.
  if (result.anonId === null) {
    ingestRequests.inc({ outcome: 'rejected' });
    return empty(400);
  }

  // After enrichment, because the key is the derived anonymous id. Deriving it is cheaper
  // than the parse that already happened, so nothing is saved by limiting earlier.
  const decision = await env.INGEST_LIMITER.limit({ key: result.anonId });
  if (!decision.success) {
    ingestRequests.inc({ outcome: 'rate_limited' });
    ingestErrors.inc({ reason: 'rate_limited' });
    return empty(429, { 'retry-after': String(RATE_LIMIT_PERIOD_SECONDS) });
  }

  if (result.events.length === 0) {
    // Everything in the batch was rejected. Nothing to publish, and nothing the client
    // can usefully do about it.
    ingestRequests.inc({ outcome: 'accepted' });
    return empty(202);
  }

  publisher.publish(result.events);
  recordLag(result.events);

  // Deferred rather than awaited. The beacon cannot act on whether the fold succeeded and
  // the browser has already discarded the response, so making page unload wait on a chain
  // of object calls would buy the visitor nothing. `waitUntil` is what keeps the work
  // guaranteed to run without keeping the response waiting for it — and `ctx` is passed
  // whole rather than destructured, because a detached `waitUntil` loses its `this`.
  ctx.waitUntil(foldSessions(env, result.events));

  ingestRequests.inc({ outcome: 'accepted' });
  ingestEvents.inc(result.events.length);
  return empty(202);
}

/**
 * Hand each session's events to its own object, so they can be folded when it ends.
 *
 * Grouped by session first: a beacon is normally one session's flush, but a batch replayed
 * from an offline queue can carry two, and sending them as one would merge a visitor's
 * morning into their afternoon.
 *
 * One call per session per beacon rather than one per event. At the design target that is
 * the difference between roughly a million object requests a day and five million, and the
 * fold is order-independent so there is nothing to gain by sending them separately.
 */
function foldSessions(env: Env, events: readonly IngestEvent[]): Promise<void> {
  const bySession = new Map<string, FoldableEvent[]>();

  for (const event of events) {
    const foldable: FoldableEvent = {
      type: event.type,
      ts: Date.parse(event.ts),
      value: event.value,
      surfaces: event.surfaces,
      variants: event.variants,
      assignmentHash: event.assignmentHash,
      holdout: event.holdout,
      botScore: event.botScore,
      // Derived here rather than in the fold, because bucketing is a decision about the
      // covariate space and `packages/core` owns it. The fold only groups by what it is
      // handed.
      contextBucket: bucketOf(event.ctx),
      isReturning: event.ctx.returning,
    };

    const batch = bySession.get(event.sessionId) ?? [];
    batch.push(foldable);
    bySession.set(event.sessionId, batch);
  }

  return Promise.all(
    [...bySession].map(async ([sessionId, batch]) => {
      const stub = env.SESSIONS.get(env.SESSIONS.idFromName(sessionId));
      await stub.record(batch);
    }),
  ).then(() => undefined);
}

/**
 * How far behind each event was when it arrived.
 *
 * Reported per event rather than per batch: a beacon replayed from an offline queue
 * carries events minutes apart, and averaging them into one number would hide exactly the
 * distribution this metric exists to show.
 */
function recordLag(events: readonly IngestEvent[]): void {
  const now = Date.now();
  for (const event of events) {
    const lag = now - Date.parse(event.ts);
    if (lag >= 0) ingestLagMs.observe(lag);
  }
}

/**
 * Re-exported so the runtime can find the class.
 *
 * A Durable Object is addressed through a binding, but the class itself has to be an
 * export of the Worker's entry module — `wrangler.jsonc` names it as a string and the
 * runtime resolves it here. Without this line the binding exists and every call to it
 * fails at runtime with a class it cannot find.
 */
export { SurfaceCounters } from './counters';
export { SessionAggregate } from './session';

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);

    // Installed per request because the binding only exists inside one. It is a property
    // of the deployment rather than of the request, so re-installing is idempotent —
    // `@morph/metrics/sink.ts` sets out why that distinction makes this safe.
    installTelemetry(env);

    if (url.pathname === '/i') {
      if (request.method !== 'POST') return empty(405, { allow: 'POST' });

      try {
        return await handleIngest(request, env, ctx, analyticsEventPublisher(env.EVENTS));
      } catch (error) {
        // Explicit, rather than `passThroughOnException`: the collector should fail
        // visibly and return a status the client's retry queue understands. 503 and not
        // 500, because a 5xx that is not explicitly retryable tends to be dropped.
        ingestRequests.inc({ outcome: 'sink_failure' });
        ingestErrors.inc({ reason: 'unhandled' });
        console.error(
          JSON.stringify({
            event: 'ingest.unhandled',
            message: error instanceof Error ? error.message : String(error),
          }),
        );
        return empty(503, { 'retry-after': '5' });
      }
    }

    if (url.pathname === '/health') {
      return Response.json({ ok: true });
    }

    if (url.pathname === '/ready') {
      // Two checks, both of which make the collector worse than useless when they fail
      // rather than merely degraded.
      //
      // A missing pepper means every visitor hashes to the same id — the data would look
      // plausible and be fiction. A missing controller means measuring people who have not
      // been told who is responsible, which is not a quality problem but an unlawful one.
      //
      // The missing variables are named in the response: "not ready" with no reason sends
      // somebody into the source at the worst possible moment.
      const missing = [
        ...(usablePepper(env) === null ? ['ANON_ID_PEPPER'] : []),
        ...missingControllerFields(env),
      ];

      return Response.json(
        { ready: missing.length === 0, missing },
        { status: missing.length === 0 ? 200 : 503 },
      );
    }

    // Everything else is closed. There is no public API here, and an open 404 surface is
    // one more thing to reason about.
    return empty(404);
  },
} satisfies ExportedHandler<Env>;

/**
 * Point `@morph/metrics` at this deployment's dataset.
 *
 * Called on every request because the binding only exists inside one. The sink defaults to
 * dropping, so skipping this would leave the collector silently unmonitored — and a
 * collector nobody can see is the one service where that matters most, since its failure
 * mode is a beacon that vanishes rather than a page that breaks.
 */
function installTelemetry(env: Env): void {
  installMetricSink(analyticsEngineSink(env.METRICS, 'api'));
}
