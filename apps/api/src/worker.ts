/**
 * The event collector, as a Cloudflare Worker (D31, D34).
 *
 * Replaces the Fastify server and its Redpanda producer. What did not change is everything
 * that decides whether a number is trustworthy: `enrich`, `classify` and the zod boundary
 * are untouched, because none of them ever knew what framework they were under.
 *
 * WHAT THIS ROUTE IS SHAPED BY
 * It runs thousands of times a second and its client is a page being unloaded:
 *
 *  - **202 Accepted** as soon as the batch is handed to Analytics Engine. The client
 *    cannot act on a durability answer and waiting for one would couple page unload to
 *    somebody else's storage.
 *  - **Empty body.** A beacon's response is discarded by the browser; JSON would be
 *    200 bytes of pure waste per request.
 *  - **No logging on the happy path.** At this rate one line per request is the largest
 *    write in the system. A rejection is counted, not logged: a client bug would
 *    otherwise produce millions of identical lines, and the counter is what alerts.
 *
 * THE BUG THIS FIXES
 * The Fastify version read `x-real-ip`, which Caddy set from the TCP peer. Put Cloudflare
 * in front of that and the peer is a Cloudflare PoP, so every visitor through one
 * datacentre collapses into a single anonymous id — and since the rate limiter is keyed on
 * that id, an entire PoP would have shared one bucket and the collector would have
 * answered 429 to almost everything. `cf-connecting-ip` is set by the edge itself, cannot
 * be spoofed by a client, and is the only header here worth believing.
 */

